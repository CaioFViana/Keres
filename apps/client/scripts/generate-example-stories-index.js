const fs = require('fs');
const path = require('path');

// Metro/TS precisam de imports estáticos - não dá para listar uma pasta em runtime como se
// faria em Node puro. Este script resolve isso do mesmo jeito que
// `generate-migrations-index.js` resolve para as migrações SQL: varre `content/` uma vez, na
// hora do build (`prestart`), e escreve um índice com um `import` por arquivo encontrado.
// Cada história de exemplo é uma pasta em `content/<slug>/`, e cada arquivo dentro dela
// (`<lang>.json`) é a mesma história num idioma diferente.

const contentDir = path.join(__dirname, '../src/exampleStories/content');
const generatedDir = path.join(__dirname, '../src/exampleStories/generated');
const outputFilePath = path.join(generatedDir, 'registry.ts');

console.log('Generating example stories registry...');

if (!fs.existsSync(generatedDir)) {
  fs.mkdirSync(generatedDir, { recursive: true });
}

function toImportName(slug, language) {
  const camelSlug = slug.replace(/[^a-zA-Z0-9]+(.)?/g, (_, ch) => (ch ? ch.toUpperCase() : ''));
  const safeSlug = /^[0-9]/.test(camelSlug) ? `_${camelSlug}` : camelSlug;
  return `${safeSlug}_${language}`;
}

try {
  const slugs = fs.existsSync(contentDir)
    ? fs
        .readdirSync(contentDir)
        .filter((entry) => fs.statSync(path.join(contentDir, entry)).isDirectory())
        .sort()
    : [];

  let imports = '';
  let entries = '';

  for (const slug of slugs) {
    const slugDir = path.join(contentDir, slug);
    const languageFiles = fs
      .readdirSync(slugDir)
      .filter((file) => file.endsWith('.json'))
      .sort();
    if (languageFiles.length === 0) continue;

    const languageLines = languageFiles
      .map((file) => {
        const language = path.basename(file, '.json');
        const importName = toImportName(slug, language);
        imports += `import ${importName} from '../content/${slug}/${file}';\n`;
        return `      { language: '${language}', story: ${importName} },`;
      })
      .join('\n');

    entries += `  {
    slug: '${slug}',
    languages: [
${languageLines}
    ],
  },
`;
  }

  const fileContent = `// This file is auto-generated by generate-example-stories-index.js
// Do not modify this file directly.
import type { ExampleStoryEntry } from '../types';

${imports}
export const exampleStoryRegistry: ExampleStoryEntry[] = [
${entries.trimEnd()}
];
`;

  fs.writeFileSync(outputFilePath, fileContent);
  console.log(
    `Example stories registry generated successfully at: ${outputFilePath} (${slugs.length} example stor${slugs.length === 1 ? 'y' : 'ies'})`,
  );
} catch (error) {
  console.error('Error generating example stories registry:', error);
  process.exit(1);
}
