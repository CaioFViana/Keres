const fs = require('fs');
const path = require('path');

const drizzleMigrationsDir = path.join(__dirname, '../drizzle');
const clientMigrationsDir = path.join(__dirname, '../src/db/migrations');
const outputFilePath = path.join(clientMigrationsDir, 'index.ts');

console.log('Generating migrations index and converting SQL to TS...');

// Ensure clientMigrationsDir exists
if (!fs.existsSync(clientMigrationsDir)) {
  fs.mkdirSync(clientMigrationsDir, { recursive: true });
}

try {
  const drizzleMigrationFiles = fs
    .readdirSync(drizzleMigrationsDir)
    .filter((file) => file.endsWith('.sql'))
    .sort();

  let imports = '';
  let migrationArray = '';

  drizzleMigrationFiles.forEach((file, index) => {
    const fileNameWithoutExt = path.basename(file, '.sql');
    const sqlContent = fs.readFileSync(path.join(drizzleMigrationsDir, file), 'utf8');

    // Create the .ts migration file in clientMigrationsDir
    const tsMigrationContent = `import { SQLiteDatabase } from 'expo-sqlite';

export default async function (db: SQLiteDatabase) {
  await db.execAsync(\`
  ${sqlContent.replace(/`/g, '"')}
\`);
}
`;
    fs.writeFileSync(
      path.join(clientMigrationsDir, `${fileNameWithoutExt}.ts`),
      tsMigrationContent,
    );

    const migrationName = `migration_${index + 1}`;
    imports += `import ${migrationName} from './${fileNameWithoutExt}';
`;
    migrationArray += `  { id: ${index + 1}, name: '${fileNameWithoutExt}', run: ${migrationName} },
`;
  });

  const fileContent = `// This file is auto-generated by generate-migrations-index.js
// Do not modify this file directly.

${imports}

const migrations = [
${migrationArray.trim()}
];

export default migrations;
`;

  fs.writeFileSync(outputFilePath, fileContent);
  console.log('Migrations index generated successfully at:', outputFilePath);
} catch (error) {
  console.error('Error generating migrations index:', error);
  process.exit(1);
}
