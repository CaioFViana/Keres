const fs = require('fs');
const path = require('path');

/**
 * Gera o registry de uma biblioteca de documentação (Ajuda ou Recursos Literários) a partir das
 * pastas de conteúdo: uma pasta por página, um arquivo por idioma.
 */
function generateDocRegistry({
  contentDir,
  outputFile,
  typeName,
  registryName,
  pageTypeImport,
  scriptName,
}) {
  const generatedDir = path.dirname(outputFile);
  fs.mkdirSync(generatedDir, { recursive: true });
  const toName = (id, language) =>
    `${id.replace(/[^a-zA-Z0-9]+(.)?/g, (_, char) => (char ? char.toUpperCase() : ''))}_${language}`;
  const propertyKey = (value) =>
    /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(value) ? value : `'${value.replace(/'/g, "\'")}'`;
  const ids = fs
    .readdirSync(contentDir)
    .filter((entry) => fs.statSync(path.join(contentDir, entry)).isDirectory())
    .sort();
  let imports = '';
  let entries = '';
  for (const id of ids) {
    const languages = fs
      .readdirSync(path.join(contentDir, id))
      .filter((file) => file.endsWith('.ts'))
      .map((file) => path.basename(file, '.ts'))
      .sort();
    const languageEntries = languages
      .map((language) => {
        const name = toName(id, language);
        imports += `import ${name} from '../content/${id}/${language}';\n`;
        return `    ${propertyKey(language)}: ${name},`;
      })
      .join('\n');
    entries += `  ${propertyKey(id)}: {\n${languageEntries}\n  },\n`;
  }
  const union = ids.length ? `\n${ids.map((id) => `  | '${id}'`).join('\n')}` : 'never';
  fs.writeFileSync(
    outputFile,
    `// Auto-generated by ${scriptName}. Do not edit.\n${pageTypeImport}\n\n${imports}\nexport type ${typeName} =${union};\n\nexport const ${registryName}: Record<${typeName}, Record<string, HelpPage>> = {\n${entries}};\n`,
  );
  console.log(`Generated registry with ${ids.length} pages at ${outputFile}`);
}

module.exports = { generateDocRegistry };
