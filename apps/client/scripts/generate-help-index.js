const fs = require('fs');
const path = require('path');
const contentDir = path.join(__dirname, '../src/help/content');
const generatedDir = path.join(__dirname, '../src/help/generated');
const output = path.join(generatedDir, 'registry.ts');
fs.mkdirSync(generatedDir, { recursive: true });
const toName = (id, language) =>
  `${id.replace(/[^a-zA-Z0-9]+(.)?/g, (_, char) => (char ? char.toUpperCase() : ''))}_${language}`;
const ids = fs
  .readdirSync(contentDir)
  .filter((entry) => fs.statSync(path.join(contentDir, entry)).isDirectory())
  .sort();
let imports = '';
let entries = '';
for (const id of ids) {
  const languages = fs
    .readdirSync(path.join(contentDir, id))
    .filter((file) => file.endsWith('.ts'))
    .map((file) => path.basename(file, '.ts'))
    .sort();
  const languageEntries = languages
    .map((language) => {
      const name = toName(id, language);
      imports += `import ${name} from '../content/${id}/${language}';\n`;
      return `    ${JSON.stringify(language)}: ${name},`;
    })
    .join('\n');
  entries += `  ${JSON.stringify(id)}: {\n${languageEntries}\n  },\n`;
}
const union = ids.map((id) => JSON.stringify(id)).join(' | ') || 'never';
fs.writeFileSync(
  output,
  `// Auto-generated by generate-help-index.js. Do not edit.\nimport type { HelpPage } from '../types';\n\n${imports}\nexport type GeneratedHelpPageId = ${union};\n\nexport const helpRegistry: Record<GeneratedHelpPageId, Record<string, HelpPage>> = {\n${entries}};\n`,
);
console.log(`Generated help registry with ${ids.length} pages at ${output}`);
